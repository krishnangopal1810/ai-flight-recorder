package cli

import (
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"github.com/krishnangopal1810/ai-flight-recorder/internal/types"
)

func newSchema() *cobra.Command {
	command := &cobra.Command{Use: "schema", Short: "Manage public generated contracts"}
	var output, source string
	generate := &cobra.Command{Use: "generate", Short: "Generate checked-in schema references", RunE: func(_ *cobra.Command, _ []string) error { return generateSchemas(source, output) }}
	generate.Flags().StringVar(&output, "output", "docs/generated", "output directory")
	generate.Flags().StringVar(&source, "source", ".", "repository root containing schemas/ and api/")
	command.AddCommand(generate)
	return command
}

func newHelpMarkdown(root *cobra.Command) *cobra.Command {
	help := &cobra.Command{Use: "help", Short: "Generate help artifacts"}
	help.AddCommand(&cobra.Command{Use: "markdown", Short: "Print CLI reference as Markdown", RunE: func(_ *cobra.Command, _ []string) error {
		_, err := io.WriteString(os.Stdout, markdownHelp(root))
		return err
	}})
	return help
}

func generateSchemas(source, output string) error {
	if err := os.MkdirAll(output, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(filepath.Join(source, "schemas"))
	if err != nil {
		return types.NewError(types.ErrBuild, "cannot enumerate schema sources", "run from the repository root or set --source", err)
	}
	files := map[string]string{"api/openapi.yaml": "openapi.yaml"}
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".json") {
			files[filepath.Join("schemas", entry.Name())] = entry.Name()
		}
	}
	for input, name := range files {
		data, err := os.ReadFile(filepath.Join(source, input))
		if err != nil {
			return types.NewError(types.ErrBuild, "cannot read schema source", "run from the repository root or set --source", err)
		}
		if name == "openapi.yaml" {
			data = []byte(strings.ReplaceAll(string(data), "../schemas/", ""))
		}
		if err := os.WriteFile(filepath.Join(output, name), data, 0o644); err != nil {
			return err
		}
	}
	database := "# Database schema\n\nGenerated from the V1 repository contract.\n\n- `capsules`: immutable manifests and searchable identity fields\n- `payloads`: content-addressed blob metadata and reference counts\n- `capsule_payloads`: manifest-to-blob references\n- `quarantine_records`: policy-safe ingest diagnostics\n- `tokens`: hashed scoped bearer tokens\n- `jobs` and `job_events`: durable leased work and SSE history\n- `evaluators` and `evaluator_runs`: versioned incident gates and their evidence\n- `audit_events`: payload-free administrative and retention evidence\n"
	return os.WriteFile(filepath.Join(output, "database-schema.md"), []byte(database), 0o644)
}

func markdownHelp(root *cobra.Command) string {
	var builder strings.Builder
	builder.WriteString("# CLI reference\n\nGenerated by `flight help markdown`.\n\n")
	commands := []*cobra.Command{}
	var collect func(*cobra.Command)
	collect = func(command *cobra.Command) {
		commands = append(commands, command)
		for _, child := range command.Commands() {
			collect(child)
		}
	}
	collect(root)
	sort.SliceStable(commands, func(i, j int) bool { return commands[i].CommandPath() < commands[j].CommandPath() })
	for _, command := range commands {
		if command.Hidden {
			continue
		}
		builder.WriteString("## `" + command.CommandPath() + "`\n\n" + command.Short + "\n\n```text\n" + command.UseLine() + "\n```\n\n")
	}
	return strings.TrimRight(builder.String(), "\n") + "\n"
}
