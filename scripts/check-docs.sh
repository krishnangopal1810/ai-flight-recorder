#!/usr/bin/env bash
set -euo pipefail

python3 - <<'PY'
from pathlib import Path
import json
import re

root = Path('.')
docs = [Path('AGENTS.md'), Path('ARCHITECTURE.md'), *Path('docs').rglob('*.md')]
missing = []
for doc in docs:
    text = doc.read_text()
    for target in re.findall(r'\[[^]]+\]\(([^)]+)\)', text):
        if target.startswith(('http://', 'https://', '#')):
            continue
        target_path = target.split('#', 1)[0]
        if target_path and not (doc.parent / target_path).resolve().exists():
            missing.append(f'{doc}: missing link target {target}')
if len(Path('AGENTS.md').read_text().splitlines()) > 100:
    missing.append('AGENTS.md: exceeds 100 lines; keep it a map and move detail into docs/')
required = {
    'docs/design-docs/index.md': ['Status', 'Last verified', 'Owner'],
    'docs/product-specs/index.md': ['Status', 'Owner'],
}
for name, terms in required.items():
    text = Path(name).read_text()
    for term in terms:
        if term not in text:
            missing.append(f'{name}: missing required index column {term}')
schema_ids = {}
for schema in Path('schemas').glob('*.json'):
    document = json.loads(schema.read_text())
    schema_id = document.get('$id')
    if not schema_id:
        missing.append(f'{schema}: missing $id')
    elif schema_id in schema_ids:
        missing.append(f'{schema}: duplicate $id also used by {schema_ids[schema_id]}')
    else:
        schema_ids[schema_id] = schema
design_index = Path('docs/design-docs/index.md').read_text()
for design in Path('docs/design-docs').glob('*.md'):
    if design.name != 'index.md' and design.name not in design_index:
        missing.append(f'{design}: missing from design-doc index')
generated_index = Path('docs/generated/index.md').read_text()
for schema in Path('schemas').glob('*.json'):
    generated = Path('docs/generated') / schema.name
    if schema.name not in generated_index:
        missing.append(f'{schema}: missing from generated reference index')
    if not generated.exists() or schema.read_bytes() != generated.read_bytes():
        missing.append(f'{generated}: stale; run make generate')
source_openapi = Path('api/openapi.yaml').read_text()
expected_openapi = source_openapi.replace('../schemas/', '')
if Path('docs/generated/openapi.yaml').read_text() != expected_openapi:
    missing.append('docs/generated/openapi.yaml: stale; run make generate')
for reference in re.findall(r"\$ref:\s*['\"]([^'\"]+\.json)['\"]", source_openapi):
    if reference.startswith('#'):
        continue
    if not (Path('api') / reference).resolve().exists():
        missing.append(f'api/openapi.yaml: unresolved schema reference {reference}')
cli_reference = Path('docs/generated/cli.md').read_text()
for command in ['capsule import', 'capsule export', 'capsule completeness', 'replay', 'diff', 'evaluator export', 'token revoke', 'bisect', 'demo seed', 'demo seed-incomplete']:
    if f'flight {command}' not in cli_reference:
        missing.append(f'docs/generated/cli.md: missing public command flight {command}; run make generate')
for plan in Path('docs/exec-plans/active').glob('*.md'):
    text = plan.read_text()
    for heading in ['## Traceability', '## Progress', '## Decisions', '## Validation evidence']:
        if heading not in text:
            missing.append(f'{plan}: missing execution-plan section {heading}')
api_client = Path('web/src/api.ts').read_text()
if 'from "./generated/openapi"' not in api_client:
    missing.append('web/src/api.ts: inspector types must come from the generated OpenAPI contract')
generated_client = Path('web/src/generated/openapi.ts')
if not generated_client.exists() or 'This file was auto-generated by openapi-typescript' not in generated_client.read_text():
    missing.append('web/src/generated/openapi.ts: missing generated client; run make generate')
if missing:
    raise SystemExit('\n'.join(missing))
print(f'docs-check: validated {len(docs)} Markdown files')
PY
